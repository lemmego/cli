// Package searchable declares what this application exposes to search.
//
// A descriptor per searchable thing, in one place, because "what can be
// found and who may find it" is a question that should be answerable by
// reading one file rather than by grepping the handlers.
package searchable

import (
	"context"
	"database/sql"
	"fmt"
	"strconv"

	"github.com/lemmego/search"
)

// Notes is the worked example: one table, searched over the tsvector column
// its migration generated.
//
// The module searches columns this application already has rather than
// keeping an index of its own, which is why there is nothing to sync for
// this engine: the column is generated by the database, so it is up to date
// the moment the row is written.
func Notes() search.Table {
	return search.Table{
		Name:  "notes",
		Label: "Notes",
		From:  "notes",

		// The generated column, with its GIN index. Named here and created
		// in the migration — the two have to agree, and the migration is the
		// one that can be wrong silently: a missing index still answers, just
		// with a sequential scan.
		Vector: "search_vector",

		ID:       "id",
		Title:    "title",
		Subtitle: "author",

		// Where a snippet is cut from. The column is read, escaped and then
		// marked up — in that order, which is the one thing in this module
		// that is load-bearing for XSS: ts_headline returns the document
		// itself, so escaping afterwards would escape the markup too and
		// escaping nothing would publish the document's own HTML.
		Snippet: []string{"body"},

		// **Required, and a table without one is refused rather than
		// searched.** That refusal is the feature: the default for a missing
		// rule cannot be "search every row", because the one time somebody
		// forgets it the result is a search box that returns other people's
		// records.
		//
		// This example's rule is "published notes only". A rule that needs
		// to know who is asking writes the placeholder, which is bound as a
		// parameter rather than interpolated:
		//
		//	Visible: "published = true OR author_id = " + search.ViewerPlaceholder,
		Visible: "published = true",
	}
}

// NotesImporter walks the table for `lemmego run search:import`.
//
// Meaningless to the Postgres engine, which has no index of its own to fill,
// and present because this is the shape every other engine needs: switching
// to Meilisearch is then a configuration change plus one import run, rather
// than writing a walker under time pressure.
//
// Keyset paging rather than an offset, which is what an import of a growing
// table wants: an offset into a table being written to skips and repeats
// rows, and the symptom is a few documents missing from the index.
type NotesImporter struct {
	DB *sql.DB
}

func (n NotesImporter) SearchIndex() string { return "notes" }

func (n NotesImporter) SearchBatch(ctx context.Context, after search.Cursor) ([]search.Document, search.Cursor, error) {
	const batch = 500

	// Parsed to a number rather than passed through as the string the cursor
	// carries. The cursor is a string because a key is a string for every
	// engine, but this column is a bigint and Postgres refuses to compare one
	// against a text parameter — so the conversion happens here, where the
	// column's type is known, rather than with a cast in the SQL.
	var afterID int64
	if after.AfterKey != "" {
		parsed, err := strconv.ParseInt(after.AfterKey, 10, 64)
		if err != nil {
			return nil, after, fmt.Errorf("bad cursor %q: %w", after.AfterKey, err)
		}
		afterID = parsed
	}

	rows, err := n.DB.QueryContext(ctx,
		`SELECT id, title, author, body
		   FROM notes
		  WHERE published = true AND id > $1
	   ORDER BY id
		  LIMIT $2`, afterID, batch)
	if err != nil {
		return nil, after, fmt.Errorf("reading notes: %w", err)
	}
	defer rows.Close()

	var (
		docs []search.Document
		last string
	)
	for rows.Next() {
		var (
			id                  int64
			title, author, body string
		)
		if err := rows.Scan(&id, &title, &author, &body); err != nil {
			return nil, after, err
		}
		last = fmt.Sprint(id)
		docs = append(docs, search.Document{
			Index: "notes",
			// A string, because every external engine keys by one — and
			// validated rather than transformed, so a key that will not
			// travel is found out on the first import instead of after a
			// year of rows.
			Key: last,
			Fields: map[string]any{
				"title":  title,
				"author": author,
				"body":   body,
			},
		})
	}
	if err := rows.Err(); err != nil {
		return nil, after, err
	}

	return docs, search.Cursor{AfterKey: last}, nil
}

var _ search.Importable = NotesImporter{}
